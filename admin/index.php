include('dbConnection.php');
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $csrf = $_POST['csrf_token'] ?? null;
    if (!is_string($csrf) || !hash_equals($_SESSION['csrf_token'], $csrf)) { http_response_code(403); exit('Invalid security token.'); }
    require_once __DIR__ . '/../app/Helpers/LoginThrottle.php';
    try {
        $retryAfter = \App\Helpers\LoginThrottle::consume('admin:' . ($_SERVER['REMOTE_ADDR'] ?? 'unknown'));
    } catch (\Throwable $e) { http_response_code(503); exit('Login temporarily unavailable.'); }
    if ($retryAfter > 0) { http_response_code(429); header('Retry-After: ' . $retryAfter); exit('Too many login attempts.'); }
    $username = trim($_POST['username'] ?? '');
    $password = trim($_POST['pwd'] ?? '');

    // Validate input
    if (empty($username) || empty($password)) {
        $error = "Username and Password are required.";
    } else {
        // Prepared SQL statement to prevent SQL injection
        $stmt = mysqli_prepare($conn, "SELECT ID, TYPE, USER_NAME, PASSWORD, NAME FROM ca_admin WHERE USER_NAME = ?");
        if ($stmt) {
            mysqli_stmt_bind_param($stmt, "s", $username);
            mysqli_stmt_execute($stmt);
            $result = mysqli_stmt_get_result($stmt);
            $user = $result ? mysqli_fetch_assoc($result) : null;
            mysqli_stmt_close($stmt);

            if ($user) {
                $storedPassword = (string)($user['PASSWORD'] ?? '');
                $passwordValid = false;
                $needsRehash = false;

                // Normalize bcrypt prefix if generated by Node.js ($2b$ or $2a$)
                $checkHash = $storedPassword;
                if (str_starts_with($checkHash, '$2b$') || str_starts_with($checkHash, '$2a$')) {
                    $checkHash = '$2y$' . substr($checkHash, 4);
                }

                // Check hashed password
                if (password_verify($password, $checkHash)) {
                    $passwordValid = true;
                }
                // Fallback for legacy plain-text password
                elseif ((password_get_info($checkHash)['algoName'] ?? 'unknown') === 'unknown' && hash_equals($storedPassword, $password)) {
                    $passwordValid = true;
                    $needsRehash = true;
                }

                if ($passwordValid) {
                    // Upgrade legacy plain-text password to bcrypt hash
                    if ($needsRehash) {
                        $newHash = password_hash($password, PASSWORD_DEFAULT);
                        $updateStmt = mysqli_prepare($conn, "UPDATE ca_admin SET PASSWORD = ? WHERE ID = ?");
                        if ($updateStmt) {
                            mysqli_stmt_bind_param($updateStmt, "si", $newHash, $user['ID']);
                            mysqli_stmt_execute($updateStmt);
                            mysqli_stmt_close($updateStmt);
                        }
                    }

                    if (!session_regenerate_id(true)) { http_response_code(500); exit('Unable to renew session.'); }
                    $_SESSION = ['admin_authenticated' => true, 'csrf_token' => bin2hex(random_bytes(32))];
                    $_SESSION['user_id'] = $user['ID'];
                    $_SESSION['username'] = $user['USER_NAME'];
                    $_SESSION['type'] = $user['TYPE'] ?? '';
                    $_SESSION['name'] = $user['NAME'] ?? $user['USER_NAME'];

                    header("Location: manage_user.php");
                    exit();
                } else {
                    $error = "Invalid Username or Password.";
                }
            } else {
                $error = "Invalid Username or Password.";
            }
        } else {
            $error = "Database query failed.";
        }
    }
}

